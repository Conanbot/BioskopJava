    // ── Data population ───────────────────────────────────────────────────────

    public void populateTable(List<Film> films) {
        currentFilms = new ArrayList<>(films);
        tableModel.setRowCount(0);
        for (Film f : films) {
            String posterDisplay = "-";
            if (f.getPosterPath() != null && !f.getPosterPath().isBlank()) {
                String p = f.getPosterPath().trim().replace('\\', '/');
                int slash = p.lastIndexOf('/');
                posterDisplay = slash >= 0 && slash + 1 < p.length() ? p.substring(slash + 1) : p;
            }
            tableModel.addRow(new Object[]{
                    f.getId(),
                    f.getTitle(),
                    f.getGenre(),
                    f.getDurationMinutes(),
                    f.getAgeRating(),
                    f.getStatus(),
                    posterDisplay
            });
        }
        updateButtonStates();
    }

    public Film getSelectedFilm() {
        int row = table.getSelectedRow();
        if (row < 0 || row >= currentFilms.size()) {
            return null;
        }
        return currentFilms.get(row);
    }

    public String getSearchKeyword() {
        return searchField.getText().trim();
    }

    public void clearSearch() {
        searchField.setText("");
    }

    private void updateButtonStates() {
        boolean hasSelection = table.getSelectedRow() >= 0;
        editButton.setEnabled(hasSelection);
        deleteButton.setEnabled(hasSelection);
    }

