    private void postInit(Window owner, Film editFilm) {
        titleLabel.setText(editFilm == null ? "Tambah Film Baru" : "Edit Data Film");
        saveButton.setText(editFilm == null ? "Simpan" : "Perbarui");

        SwingTheme.styleButton(saveButton, true);
        saveButton.setPreferredSize(new Dimension(115, 40));
        SwingTheme.styleButton(cancelButton, false);
        cancelButton.setPreferredSize(new Dimension(105, 40));

        saveButton.addActionListener(e -> {
            if (validateInput()) {
                confirmed = true;
                dispose();
            }
        });
        cancelButton.addActionListener(e -> dispose());
        filmTitleField.addActionListener(e -> genreField.requestFocusInWindow());
        getRootPane().registerKeyboardAction(
                e -> dispose(),
                javax.swing.KeyStroke.getKeyStroke(java.awt.event.KeyEvent.VK_ESCAPE, 0),
                javax.swing.JComponent.WHEN_IN_FOCUSED_WINDOW);

        if (editFilm != null) {
            prefillForm(editFilm);
        }

        SwingTheme.applyFont(this);
        pack();
        setLocationRelativeTo(owner);
    }

    private void prefillForm(Film film) {
        filmTitleField.setText(film.getTitle());
        genreField.setText(film.getGenre());
        durationSpinner.setValue(film.getDurationMinutes());
        ageRatingCombo.setSelectedItem(film.getAgeRating());
        statusCombo.setSelectedItem(film.getStatus());
        synopsisArea.setText(film.getSynopsis());
        if (film.getPosterPath() != null) {
            posterPathField.setText(film.getPosterPath());
        }
    }

    private void handleBrowsePoster() {
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Pilih Gambar Poster Film");
        fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter(
                "File Gambar (*.jpg, *.jpeg, *.png, *.webp)", "jpg", "jpeg", "png", "webp"));
        int res = fileChooser.showOpenDialog(this);
        if (res == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File selectedFile = fileChooser.getSelectedFile();
            posterPathField.setText(selectedFile.getAbsolutePath());
        }
    }

    private boolean validateInput() {
        String title = filmTitleField.getText().trim();
        if (title.isEmpty()) {
            errorLabel.setText("Judul film wajib diisi.");
            return false;
        }
        if (title.length() > 150) {
            errorLabel.setText("Judul film maksimal 150 karakter.");
            return false;
        }

        String genre = genreField.getText().trim();
        if (genre.isEmpty()) {
            errorLabel.setText("Genre film wajib diisi.");
            return false;
        }
        if (genre.length() > 80) {
            errorLabel.setText("Genre maksimal 80 karakter.");
            return false;
        }

        int duration = (int) durationSpinner.getValue();
        if (duration <= 0) {
            errorLabel.setText("Durasi film harus lebih dari 0 menit.");
            return false;
        }

        String synopsis = synopsisArea.getText().trim();
        if (synopsis.isEmpty()) {
            errorLabel.setText("Sinopsis film wajib diisi.");
            return false;
        }

        errorLabel.setText(" ");
        return true;
    }

