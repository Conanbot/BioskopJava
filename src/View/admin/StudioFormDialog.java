    private void postInit(Window owner, Studio editStudio) {
        titleLabel.setText(editStudio == null ? "Tambah Studio Baru" : "Edit Data Studio");
        saveButton.setText(editStudio == null ? "Simpan" : "Perbarui");

        SwingTheme.styleButton(saveButton, true);
        saveButton.setPreferredSize(new java.awt.Dimension(115, 40));
        SwingTheme.styleButton(cancelButton, false);
        cancelButton.setPreferredSize(new java.awt.Dimension(105, 40));

        saveButton.addActionListener(e -> {
            if (validateInput()) {
                confirmed = true;
                dispose();
            }
        });
        cancelButton.addActionListener(e -> dispose());
        nameField.addActionListener(e -> saveButton.doClick());
        getRootPane().registerKeyboardAction(
                e -> dispose(),
                javax.swing.KeyStroke.getKeyStroke(java.awt.event.KeyEvent.VK_ESCAPE, 0),
                javax.swing.JComponent.WHEN_IN_FOCUSED_WINDOW);

        if (editStudio != null) {
            prefillForm(editStudio);
        }

        SwingTheme.applyFont(this);
        pack();
        setLocationRelativeTo(owner);
    }

    private void prefillForm(Studio studio) {
        nameField.setText(studio.getName());
        rowsSpinner.setValue(studio.getSeatRows());
        colsSpinner.setValue(studio.getSeatCols());
    }

    private boolean validateInput() {
        String name = nameField.getText().trim();
        if (name.isEmpty()) {
            errorLabel.setText("Nama studio wajib diisi.");
            return false;
        }
        if (name.length() > 80) {
            errorLabel.setText("Nama studio maksimal 80 karakter.");
            return false;
        }
        errorLabel.setText(" ");
        return true;
    }

